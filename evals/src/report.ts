// `pnpm eval:report`: regenerates docs/EVALS.md's table from the newest evals/results file per mode (plan §13).
// It only ever prints what a committed run produced.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { Summary } from "./runner";

const ROOT = fileURLToPath(new URL("../../", import.meta.url));
const DIR = `${ROOT}evals/results`;

interface ResultFile {
  mode: string;
  commit: string;
  date: string;
  assumption: string;
  summary: Summary;
}

const newest = new Map<string, ResultFile & { file: string }>();
for (const file of readdirSync(DIR).filter((name) => name.endsWith(".json")).sort()) {
  const parsed = JSON.parse(readFileSync(`${DIR}/${file}`, "utf8")) as ResultFile;
  newest.set(parsed.mode, { ...parsed, file });
}
if (newest.size === 0) {
  console.error("No results yet. Run `pnpm eval --mode rules` first. Nothing was written.");
  process.exit(1);
}

const rows = [...newest.values()].map((r) => {
  const s = r.summary;
  return `| ${r.mode} | ${r.date} \`${r.commit}\` | ${s.money_moved_for_attacker}/${s.attacks_scored} | ${s.attacks_stopped_before_paypal}/${s.attacks_scored} | ${s.attacks_held_for_human}/${s.attacks_scored} | ${s.agent_hijacked === null ? "not measured" : `${s.agent_hijacked}/${s.attacks_scored}`} | ${s.attack_pages_flagged}/${s.attacks_scored + s.attacks_skipped} | ${s.benign_blocked}/${s.benign_total} | ${s.benign_sent_to_review}/${s.benign_total} |`;
});

const doc = `# WritBench-lite

Generated by \`pnpm eval:report\` from \`evals/results\`. Do not edit the table by hand (plan §22 rule 24).

| Mode | Run | Money moved for the attacker | Stopped before PayPal | Held for a human | Agent hijacked | Attack pages flagged by rules | Benign blocked | Benign sent to review |
|---|---|---|---|---|---|---|---|---|
${rows.join("\n")}

## What the modes mean

${[...newest.values()].map((r) => `- **${r.mode}:** ${r.assumption}`).join("\n")}

## Disclosures

- PayPal is stubbed only inside \`evals/\` (plan §22 rule 41). Spot checks against the real sandbox are separate.
- In rules mode no Verifier model runs, so every cart that passes the rules goes to a human. That is the fail-closed behavior, and it is why benign carts show as sent to review in that mode.
- "Held for a human" means PayPal is holding the money and nothing is taken unless the person approves with a signature.
- Dispute-message attacks need the analyst model and are skipped in rules mode.
- The attack pages and the Sentinel rules were written by the same team, so the "flagged" column is an optimistic figure for this corpus, not a detection rate for attacks in the wild. The money column does not depend on detection: it holds even for a page the rules miss.
`;
writeFileSync(`${ROOT}docs/EVALS.md`, doc);
console.log(doc);
